import { z } from "zod";

/**
 * Catálogo de códigos de error canónicos de dominio (docs/ARCHITECTURE.md §5).
 */
export const ERROR_CODES = {
  NO_AUTENTICADO: "NO_AUTENTICADO",
  CREDENCIALES_INVALIDAS: "CREDENCIALES_INVALIDAS",
  CUENTA_YA_ACTIVADA: "CUENTA_YA_ACTIVADA",
  BOX_NO_SELECCIONADO: "BOX_NO_SELECCIONADO",
  ACCESO_DENEGADO_ROL: "ACCESO_DENEGADO_ROL",
  ULTIMO_ADMINISTRADOR: "ULTIMO_ADMINISTRADOR",
  MEMBRESIA_SUPERPUESTA: "MEMBRESIA_SUPERPUESTA",
  MEMBRESIA_NO_VIGENTE: "MEMBRESIA_NO_VIGENTE",
  SIN_CREDITOS_DISPONIBLES: "SIN_CREDITOS_DISPONIBLES",
  CUPO_AGOTADO: "CUPO_AGOTADO",
  CUPO_MENOR_A_RESERVAS: "CUPO_MENOR_A_RESERVAS",
  SUPERPOSICION_HORARIA: "SUPERPOSICION_HORARIA",
  FUERA_DE_ANTICIPACION: "FUERA_DE_ANTICIPACION",
  CLASE_CANCELADA: "CLASE_CANCELADA",
  VENTANA_CORRECCION_VENCIDA: "VENTANA_CORRECCION_VENCIDA",
  PAGO_YA_ANULADO: "PAGO_YA_ANULADO",
  VALIDACION_FALLIDA: "VALIDACION_FALLIDA",
  ERROR_INTERNO: "ERROR_INTERNO"
} as const;

export const ErrorCodeSchema = z.enum([
  ERROR_CODES.NO_AUTENTICADO,
  ERROR_CODES.CREDENCIALES_INVALIDAS,
  ERROR_CODES.CUENTA_YA_ACTIVADA,
  ERROR_CODES.BOX_NO_SELECCIONADO,
  ERROR_CODES.ACCESO_DENEGADO_ROL,
  ERROR_CODES.ULTIMO_ADMINISTRADOR,
  ERROR_CODES.MEMBRESIA_SUPERPUESTA,
  ERROR_CODES.MEMBRESIA_NO_VIGENTE,
  ERROR_CODES.SIN_CREDITOS_DISPONIBLES,
  ERROR_CODES.CUPO_AGOTADO,
  ERROR_CODES.CUPO_MENOR_A_RESERVAS,
  ERROR_CODES.SUPERPOSICION_HORARIA,
  ERROR_CODES.FUERA_DE_ANTICIPACION,
  ERROR_CODES.CLASE_CANCELADA,
  ERROR_CODES.VENTANA_CORRECCION_VENCIDA,
  ERROR_CODES.PAGO_YA_ANULADO,
  ERROR_CODES.VALIDACION_FALLIDA,
  ERROR_CODES.ERROR_INTERNO
]);

export type ErrorCode = z.infer<typeof ErrorCodeSchema>;

export const ErrorResponseSchema = z.object({
  statusCode: z.number().int().min(400).max(599),
  errorCode: ErrorCodeSchema,
  message: z.string().min(1),
  details: z.record(z.string(), z.array(z.string())).nullable()
});

export type ErrorResponse = z.infer<typeof ErrorResponseSchema>;
